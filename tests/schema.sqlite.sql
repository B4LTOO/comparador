-- Esquema equivalente para SQLite. Solo se usa en las pruebas locales (tests/run.sh).
CREATE TABLE cpus (
  id INTEGER PRIMARY KEY AUTOINCREMENT, slug TEXT NOT NULL UNIQUE, name TEXT NOT NULL,
  brand TEXT NOT NULL, score INTEGER NOT NULL, source TEXT NOT NULL DEFAULT 'estimado'
);
CREATE TABLE gpus (
  id INTEGER PRIMARY KEY AUTOINCREMENT, slug TEXT NOT NULL UNIQUE, name TEXT NOT NULL,
  brand TEXT NOT NULL, score INTEGER NOT NULL, vram_gb INTEGER NOT NULL, rt_perf REAL NOT NULL DEFAULT 0.5,
  source TEXT NOT NULL DEFAULT 'estimado'
);
CREATE TABLE games (
  id INTEGER PRIMARY KEY AUTOINCREMENT, slug TEXT NOT NULL UNIQUE, name TEXT NOT NULL, tag TEXT NOT NULL,
  gpu_base INTEGER NOT NULL, cpu_base INTEGER NOT NULL, res_k REAL NOT NULL, qual_k REAL NOT NULL,
  upscaling INTEGER NOT NULL DEFAULT 0, fps_cap INTEGER NULL, ram_sens REAL NOT NULL DEFAULT 0.05,
  source TEXT NOT NULL DEFAULT 'estimado', rt_k REAL NOT NULL DEFAULT 0, fg INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE builds (
  id INTEGER PRIMARY KEY AUTOINCREMENT, code TEXT NOT NULL UNIQUE, title TEXT NULL,
  is_public INTEGER NOT NULL DEFAULT 0,
  cpu_a_id INTEGER NOT NULL REFERENCES cpus (id), gpu_a_id INTEGER NOT NULL REFERENCES gpus (id), ram_a INTEGER NOT NULL,
  cpu_b_id INTEGER NULL REFERENCES cpus (id), gpu_b_id INTEGER NULL REFERENCES gpus (id), ram_b INTEGER NULL,
  res INTEGER NOT NULL, quality TEXT NOT NULL, upscale INTEGER NOT NULL DEFAULT 0,
  rt INTEGER NOT NULL DEFAULT 0, fg INTEGER NOT NULL DEFAULT 0,
  delete_hash TEXT NOT NULL, ip_hash TEXT NOT NULL, created_at TEXT NOT NULL
);
